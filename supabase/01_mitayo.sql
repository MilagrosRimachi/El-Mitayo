-- ---------- Datos para vender (también se guardan en el celular para vender sin internet) ----------
create or replace function public.app_contexto()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  c public.sunat_config%rowtype;
begin
  if auth.uid() is null then raise exception 'Inicia sesión.'; end if;

  select * into c from sunat_config where id = 1;

  return jsonb_build_object(
    'emisor', jsonb_build_object(
      'ruc', coalesce(c.ruc, ''),
      'razon_social', coalesce(c.razon_social, ''),
      'nombre_comercial', coalesce(c.nombre_comercial, ''),
      'direccion', coalesce(c.direccion, ''),
      'lugar', concat_ws(' - ', nullif(c.distrito, ''), nullif(c.provincia, ''), nullif(c.departamento, '')),
      'telefono', coalesce(c.telefono, ''),
      'leyenda_amazonia', c.leyenda_amazonia,
      'afectacion', c.afectacion
    ),
    'ambiente', c.ambiente,
    'series', jsonb_build_object('03', c.serie_boleta, '01', c.serie_factura),
    'ultimos', jsonb_build_object(
      '03', coalesce((select ultimo from comprobante_correlativos where serie = c.serie_boleta and ambiente = c.ambiente), 0),
      '01', coalesce((select ultimo from comprobante_correlativos where serie = c.serie_factura and ambiente = c.ambiente), 0)
    ),
    'whatsapp', coalesce(c.whatsapp_contadora, '')
  );
end;
$$;

revoke all on function public.app_contexto() from public, anon;
grant execute on function public.app_contexto() to authenticated;

-- ---------- Registrar una venta (con o sin internet; no se repite) ----------
-- p_datos: { fecha, tipo '03'|'01', numero (el que salió en el ticket, opcional), metodo_pago,
--            cliente:{tipo_doc,numero,nombre,direccion}, total,
--            lineas:[{producto_id,codigo,descripcion,unidad,cantidad,precio,importe}], sin_conexion }
create or replace function public.app_venta_registrar(p_uid uuid, p_datos jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  c public.sunat_config%rowtype;
  v_existe public.ventas%rowtype;
  v_comp public.comprobantes%rowtype;
  v_tipo text := p_datos ->> 'tipo';
  v_serie text;
  v_numero integer := nullif(p_datos ->> 'numero', '')::integer;
  v_renumerado boolean := false;
  v_fecha timestamptz := coalesce(nullif(p_datos ->> 'fecha', '')::timestamptz, now());
  v_total numeric := round((p_datos ->> 'total')::numeric, 2);
  v_suma numeric;
  v_cli jsonb := coalesce(p_datos -> 'cliente', '{}'::jsonb);
  v_cli_tipo text := coalesce(nullif(v_cli ->> 'tipo_doc', ''), '0');
  v_cli_num text := coalesce(nullif(btrim(v_cli ->> 'numero'), ''), '00000000');
  v_cli_nom text := coalesce(nullif(upper(btrim(v_cli ->> 'nombre')), ''), 'CLIENTES VARIOS');
  v_cli_dir text := nullif(upper(btrim(coalesce(v_cli ->> 'direccion', ''))), '');
  v_venta bigint;
  v_comp_id bigint;
  l jsonb;
begin
  if auth.uid() is null then raise exception 'Inicia sesión.'; end if;

  -- Ya se registró (por ejemplo, se reintentó al volver el internet)
  select * into v_existe from ventas where uid = p_uid;
  if found then
    select * into v_comp from comprobantes where venta_id = v_existe.id and tipo in ('01', '03');
    return jsonb_build_object('venta_id', v_existe.id, 'comprobante_id', v_comp.id, 'serie', v_comp.serie,
                              'numero', v_comp.numero, 'renumerado', false, 'repetida', true);
  end if;

  if v_tipo not in ('01', '03') then raise exception 'Tipo de comprobante no válido.'; end if;

  if jsonb_typeof(p_datos -> 'lineas') is distinct from 'array' or jsonb_array_length(p_datos -> 'lineas') = 0 then
    raise exception 'La venta no tiene productos.';
  end if;

  select coalesce(sum(round((x ->> 'importe')::numeric, 2)), 0) into v_suma from jsonb_array_elements(p_datos -> 'lineas') x;
  if abs(v_suma - v_total) > 0.02 then raise exception 'El total no coincide con los productos.'; end if;

  if v_tipo = '01' then
    if v_cli_tipo <> '6' or v_cli_num !~ '^(10|15|16|17|20)\d{9}$' then
      raise exception 'Para factura el cliente debe tener RUC.';
    end if;
  elsif v_total > 700 and v_cli_tipo = '0' then
    raise exception 'Boletas de más de S/ 700 necesitan el DNI del cliente.';
  end if;

  select * into c from sunat_config where id = 1;
  v_serie := case when v_tipo = '01' then c.serie_factura else c.serie_boleta end;

  insert into comprobante_correlativos (serie, ambiente, ultimo) values (v_serie, c.ambiente, 0)
  on conflict (serie, ambiente) do nothing;

  perform 1 from comprobante_correlativos where serie = v_serie and ambiente = c.ambiente for update;

  -- El número que ya salió impreso se respeta si está libre; si no, se usa el siguiente
  if v_numero is null or v_numero <= 0
     or exists (select 1 from comprobantes where serie = v_serie and numero = v_numero and ambiente = c.ambiente) then
    v_renumerado := v_numero is not null;
    update comprobante_correlativos set ultimo = ultimo + 1 where serie = v_serie and ambiente = c.ambiente
    returning ultimo into v_numero;
  else
    update comprobante_correlativos set ultimo = greatest(ultimo, v_numero) where serie = v_serie and ambiente = c.ambiente;
  end if;

  insert into ventas (uid, fecha, tipo, total, metodo_pago, cliente_tipo_doc, cliente_numero, cliente_nombre, cliente_direccion, sin_conexion)
  values (p_uid, v_fecha, v_tipo, v_total, coalesce(nullif(p_datos ->> 'metodo_pago', ''), 'EFECTIVO'),
          v_cli_tipo, v_cli_num, v_cli_nom, v_cli_dir, coalesce((p_datos ->> 'sin_conexion')::boolean, false))
  returning id into v_venta;

  for l in select * from jsonb_array_elements(p_datos -> 'lineas') loop
    insert into venta_detalles (venta_id, producto_id, codigo, descripcion, unidad, cantidad, precio, importe)
    values (v_venta, nullif(l ->> 'producto_id', '')::bigint, nullif(l ->> 'codigo', ''),
            left(coalesce(nullif(btrim(l ->> 'descripcion'), ''), 'PRODUCTO'), 250),
            coalesce(nullif(l ->> 'unidad', ''), 'NIU'),
            (l ->> 'cantidad')::numeric, (l ->> 'precio')::numeric, round((l ->> 'importe')::numeric, 2));
  end loop;

  insert into comprobantes (venta_id, tipo, serie, numero, ambiente, fecha_emision, cliente_tipo_doc, cliente_numero,
                            cliente_nombre, cliente_direccion, total)
  values (v_venta, v_tipo, v_serie, v_numero, c.ambiente, v_fecha, v_cli_tipo, v_cli_num, v_cli_nom, v_cli_dir, v_total)
  returning id into v_comp_id;

  -- El cliente queda guardado para la próxima vez
  if v_cli_tipo in ('1', '6') then
    insert into clientes (tipo_doc, numero, nombre, direccion) values (v_cli_tipo, v_cli_num, v_cli_nom, v_cli_dir)
    on conflict (tipo_doc, numero) do update set nombre = excluded.nombre,
      direccion = coalesce(excluded.direccion, clientes.direccion), actualizado_en = now();
  end if;

  return jsonb_build_object('venta_id', v_venta, 'comprobante_id', v_comp_id, 'serie', v_serie, 'numero', v_numero,
                            'renumerado', v_renumerado, 'repetida', false);
end;
$$;

revoke all on function public.app_venta_registrar(uuid, jsonb) from public, anon;
grant execute on function public.app_venta_registrar(uuid, jsonb) to authenticated;

-- ---------- Productos: código nuevo automático e importación desde Excel ----------
create or replace function public.app_producto_codigo_nuevo()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select lpad((coalesce(max(case when codigo ~ '^\d{1,9}$' then codigo::bigint end), 0) + 1)::text, 5, '0') from productos;
$$;

revoke all on function public.app_producto_codigo_nuevo() from public, anon;
grant execute on function public.app_producto_codigo_nuevo() to authenticated;

-- p_filas: [{codigo, nombre, unidad, precio}] · el código ya existente se actualiza, el nuevo se crea
create or replace function public.app_productos_importar(p_filas jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  f jsonb;
  v_codigo text;
  v_creados integer := 0;
  v_actualizados integer := 0;
  v_omitidos integer := 0;
  v_nombre text;
  v_precio numeric;
begin
  if auth.uid() is null then raise exception 'Inicia sesión.'; end if;

  for f in select * from jsonb_array_elements(p_filas) loop
    v_nombre := nullif(upper(btrim(coalesce(f ->> 'nombre', ''))), '');
    v_precio := nullif(f ->> 'precio', '')::numeric;

    if v_nombre is null or v_precio is null or v_precio < 0 then
      v_omitidos := v_omitidos + 1;
      continue;
    end if;

    v_codigo := nullif(btrim(coalesce(f ->> 'codigo', '')), '');
    if v_codigo is null then v_codigo := public.app_producto_codigo_nuevo(); end if;

    if exists (select 1 from productos where codigo = v_codigo) then
      update productos set nombre = left(v_nombre, 250), precio = round(v_precio, 2),
             unidad = coalesce(nullif(f ->> 'unidad', ''), unidad), activo = true, actualizado_en = now()
       where codigo = v_codigo;
      v_actualizados := v_actualizados + 1;
    else
      insert into productos (codigo, nombre, unidad, precio)
      values (v_codigo, left(v_nombre, 250), coalesce(nullif(f ->> 'unidad', ''), 'NIU'), round(v_precio, 2));
      v_creados := v_creados + 1;
    end if;
  end loop;

  return jsonb_build_object('creados', v_creados, 'actualizados', v_actualizados, 'omitidos', v_omitidos);
end;
$$;

revoke all on function public.app_productos_importar(jsonb) from public, anon;
grant execute on function public.app_productos_importar(jsonb) to authenticated;

-- ---------- Cola de envío a SUNAT: un comprobante a la vez, reintentos espaciados ----------
create or replace function public.app_sunat_tomar(p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v public.comprobantes%rowtype;
begin
  perform pg_advisory_xact_lock(hashtext('mitayo:envio_sunat'));

  select * into v from comprobantes where id = p_id for update;
  if not found then return jsonb_build_object('ok', false, 'motivo', 'NO_EXISTE'); end if;
  if v.estado in ('ACEPTADO', 'OBSERVADO', 'RECHAZADO') then
    return jsonb_build_object('ok', false, 'motivo', 'FINAL', 'estado', v.estado);
  end if;
  if v.proximo_intento is not null and v.proximo_intento > now() then
    return jsonb_build_object('ok', false, 'motivo', 'ESPERA', 'hasta', v.proximo_intento);
  end if;
  if exists (select 1 from comprobantes where enviando_desde > now() - interval '45 seconds') then
    return jsonb_build_object('ok', false, 'motivo', 'OCUPADO');
  end if;

  update comprobantes set enviando_desde = now() where id = p_id;
  return jsonb_build_object('ok', true);
end;
$$;

create or replace function public.app_sunat_liberar(p_id bigint, p_codigo text, p_estado text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_fallos integer;
  v_prox timestamptz;
begin
  if p_estado in ('ACEPTADO', 'OBSERVADO', 'RECHAZADO') then
    update comprobantes set enviando_desde = null, proximo_intento = null, fallos_0102 = 0 where id = p_id;
    return jsonb_build_object('ok', true);
  end if;

  if p_codigo = '0102' then
    update comprobantes set fallos_0102 = fallos_0102 + 1 where id = p_id returning fallos_0102 into v_fallos;
    v_prox := now() + case when v_fallos <= 1 then interval '5 minutes'
                           when v_fallos = 2 then interval '15 minutes'
                           else interval '30 minutes' end;
  elsif p_codigo = '0140' then
    v_prox := now() + interval '20 minutes';
  elsif p_codigo = 'SIN_RESPUESTA' then
    v_prox := now() + interval '5 minutes';
  else
    v_prox := now() + interval '2 minutes';
  end if;

  update comprobantes set enviando_desde = null, proximo_intento = v_prox where id = p_id;
  return jsonb_build_object('ok', true, 'proximo_intento', v_prox);
end;
$$;

revoke all on function public.app_sunat_tomar(bigint) from public, anon, authenticated;
revoke all on function public.app_sunat_liberar(bigint, text, text) from public, anon, authenticated;
grant execute on function public.app_sunat_tomar(bigint) to service_role;
grant execute on function public.app_sunat_liberar(bigint, text, text) to service_role;
