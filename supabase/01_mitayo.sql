-- ---------- Configuración del negocio y de SUNAT (una sola fila) ----------
create table if not exists public.sunat_config (
  id integer primary key default 1 check (id = 1),
  ruc text,
  razon_social text,
  nombre_comercial text default 'MULTISERVICIOS "EL MITAYO"',
  direccion text,
  ubigeo text,
  departamento text,
  provincia text,
  distrito text,
  urbanizacion text,
  codigo_local text default '0000',
  telefono text,
  ambiente text not null default 'BETA' check (ambiente in ('BETA', 'PRODUCCION')),
  usuario_sol text,
  clave_sol_cifrada text,
  certificado_cifrado text,
  certificado_clave_cifrada text,
  certificado_titular text,
  certificado_vence timestamptz,
  afectacion text not null default '20' check (afectacion in ('10', '20', '30')),
  leyenda_amazonia boolean not null default true,
  serie_boleta text not null default 'B001',
  serie_factura text not null default 'F001',
  whatsapp_contadora text,
  actualizado_en timestamptz default now()
);

insert into public.sunat_config (id) values (1) on conflict (id) do nothing;

-- ---------- Productos (sin stock) ----------
create table if not exists public.productos (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null,
  unidad text not null default 'NIU',
  precio numeric(12, 2) not null default 0 check (precio >= 0),
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create index if not exists productos_nombre_idx on public.productos (lower(nombre));

-- ---------- Clientes (se guardan solos al vender con DNI o RUC) ----------
create table if not exists public.clientes (
  id bigint generated by default as identity primary key,
  tipo_doc text not null,
  numero text not null,
  nombre text not null,
  direccion text,
  actualizado_en timestamptz not null default now(),
  unique (tipo_doc, numero)
);

-- ---------- Ventas ----------
create table if not exists public.ventas (
  id bigint generated by default as identity primary key,
  uid uuid not null unique,
  fecha timestamptz not null default now(),
  tipo text not null check (tipo in ('01', '03')),
  total numeric(12, 2) not null check (total >= 0),
  metodo_pago text not null default 'EFECTIVO',
  estado text not null default 'CONFIRMADA' check (estado in ('CONFIRMADA', 'ANULADA')),
  cliente_tipo_doc text not null default '0',
  cliente_numero text not null default '00000000',
  cliente_nombre text not null default 'CLIENTES VARIOS',
  cliente_direccion text,
  sin_conexion boolean not null default false,
  creado_en timestamptz not null default now()
);

create index if not exists ventas_fecha_idx on public.ventas (fecha);

create table if not exists public.venta_detalles (
  id bigint generated by default as identity primary key,
  venta_id bigint not null references public.ventas (id) on delete cascade,
  producto_id bigint references public.productos (id),
  codigo text,
  descripcion text not null,
  unidad text not null default 'NIU',
  cantidad numeric(12, 3) not null check (cantidad > 0),
  precio numeric(12, 4) not null check (precio >= 0),
  importe numeric(12, 2) not null check (importe >= 0)
);

create index if not exists venta_detalles_venta_idx on public.venta_detalles (venta_id);

-- ---------- Comprobantes electrónicos ----------
create table if not exists public.comprobante_correlativos (
  serie text not null,
  ambiente text not null,
  ultimo integer not null default 0,
  primary key (serie, ambiente)
);

create table if not exists public.comprobantes (
  id bigint generated by default as identity primary key,
  venta_id bigint not null references public.ventas (id) on delete cascade,
  tipo text not null check (tipo in ('01', '03', '07')),
  serie text not null,
  numero integer not null,
  ambiente text not null check (ambiente in ('BETA', 'PRODUCCION')),
  fecha_emision timestamptz not null default now(),
  cliente_tipo_doc text not null,
  cliente_numero text not null,
  cliente_nombre text not null,
  cliente_direccion text,
  total numeric not null,
  estado text not null default 'PENDIENTE' check (estado in ('PENDIENTE', 'ACEPTADO', 'OBSERVADO', 'RECHAZADO', 'ERROR')),
  hash text,
  xml_gz text,
  cdr_gz text,
  codigo_respuesta text,
  mensaje text,
  observaciones text,
  intentos integer not null default 0,
  enviado_en timestamptz,
  enviando_desde timestamptz,
  proximo_intento timestamptz,
  fallos_0102 integer not null default 0,
  token uuid not null default gen_random_uuid(),
  ref_tipo text,
  ref_serie text,
  ref_numero integer,
  motivo_codigo text,
  motivo_texto text,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  unique (serie, numero, ambiente)
);

create index if not exists comprobantes_estado_idx on public.comprobantes (estado, proximo_intento);
create index if not exists comprobantes_venta_idx on public.comprobantes (venta_id);

